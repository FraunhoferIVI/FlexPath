def compare_two_vectors(
    v_src,
    v_tar
):
    assert v_src.shape[0] == v_tar.shape[0]
    equal = (v_tar == v_src).float().sum()
    gre = (v_tar > v_src).float().sum()
    less = (v_tar < v_src).float().sum()

    return {'less': less.cpu(), 'equal': equal.cpu(), 'gre': gre.cpu()}

